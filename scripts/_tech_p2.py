h2("2.2　六个真实踩过的坑（每个都值得记住）")
para("下面这些都不是编的，是项目里真实发生、真实修掉的。看懂这六个，你就能回答答辩里一半的技术追问。", space_after=4)

h2("坑 1　双击 index.html，页面说「数据未接通」")
para("现象：本地双击打开，图全是空的；开 npm start 就好了。", space_after=2)
para("根因：页面用 fetch 读 data/market/*.json。双击时地址是 file:///F:/...，浏览器出于安全（同源策略）"
     "禁止 file:// 页面用 fetch 读本地文件——它会认为这是网页想偷看你硬盘。", space_after=2)
para("修法：承认这个限制，README 写明「必须 npm start 后访问 http://localhost:8081/」；"
     "早期还留了一份 js/data.js 做离线降级数据，后来数据变大就废掉了。", space_after=2)
para("教训：凡是「本地文件 + fetch」，一定会在 file:// 挂。要么起服务，要么把数据写成 .js 文件（script 标签加载不受同源限制）。",
     size=9.5, color=MUTED)

h2("坑 2　实时 TOP10 的第 10 名，接口返回 404")
para("现象：抓 10 个 appid 的在线人数，第 10 个每次都失败。", space_after=2)
para("根因：Steam 那个接口对部分 appid 不返回（下架/锁区/限流），不是你的代码错。", space_after=2)
para("修法：用另一条渠道（SteamCharts 榜单镜像）补齐第 10 名，同时在 JSON 里保留抓取时间，页面上写「最近一次抓取的快照」；"
     "失败就保留旧快照 + 标注时间，绝不补一个假数字。", space_after=2)
para("教训：数据源缺点东西是常态。工程上正确的做法是「标注 + 兜底」，不是「假装完整」。"
     "答辩时这句「第 10 名接口 404，我用镜像补全并保留了时间戳」比硬说 10 个都成功更可信。", size=9.5, color=MUTED)

h2("坑 3　服务器被一个网址搞崩（进程直接退出）")
para("现象：浏览器访问一个带 % 的乱码路径，整个 node 进程退出，页面全挂。", space_after=2)
para("根因：路由里用 decodeURIComponent 解析路径，遇到非法百分号编码（比如 %E0%A4%A）会抛异常；"
     "这个异常没人接，Node 默认「未捕获异常 → 退出进程」。一个请求就把服务打死了。", space_after=2)
para("修法：写一个 safeDecode——逐段 try/catch 解码，失败就返回原串；并且把整个请求处理包在 try/catch 里，出错返回 404 而不是退出。", space_after=2)
para("教训：服务端代码必须假设「进来的东西全是脏的」。一个用户的坏请求不能让所有人的页面挂掉。", size=9.5, color=MUTED)

h2("坑 4　15 万行数据塞进浏览器，页面卡死")
para("现象：一开始想让前端直接读 29MB 的 market_full.csv，浏览器直接卡住甚至崩标签页。", space_after=2)
para("根因：浏览器里解析 15 万行 × 21 列 CSV 要几百 MB 内存，加上页面还要画图，必然卡。", space_after=2)
para("修法：把「算」搬到 Python 里做——预聚合出 1.2MB 的 JSON（各维度已统计好），前端只负责画。", space_after=2)
para("教训：这是最典型的「前后端分工」理由：浏览器只做展示，重计算留在数据层。"
     "任务书要求「CSV ≤5MB」，本项目用「CSV 留档 + 预聚合 JSON 上屏」换了个形态，报告里要主动说明。", size=9.5, color=MUTED)

h2("坑 5　价格差 100 倍：单位是「分」不是「元」")
para("现象：均价算出来 $0.05，明显不对。", space_after=2)
para("根因：archive 里 price 字段单位是「分」（499 表示 $4.99），直接当美元用就小了 100 倍；"
     "而且它是多币种，还带实时汇率，要按币种折成美元。", space_after=2)
para("修法：先 ÷100 得原币金额，再 × 快照期汇率折美元；免费（price=0）和「未标价」分开统计，不混成 0 元。", space_after=2)
para("教训：拿到任何数据，第一件事是问「单位是什么、缺失怎么表示」。这一条能救掉一半的错。", size=9.5, color=MUTED)

h2("坑 6　类型数量相加超过总数（406,518 > 150,279）")
para("现象：十个类型的数量加起来 40 万，比游戏总数 15 万还多，看着像算错了。", space_after=2)
para("根因：Steam 是多标签的，一款游戏可以同时是动作 + 独立 + 冒险。数量相加等于「类型-游戏」配对数，不是游戏数。", space_after=2)
para("修法：保留多主类型（因为它真实反映了「类型互相重叠」这个结论），同时在页面上明写「数量可重叠」；"
     "另算一个「未命中任何大类 8,870 款」补齐口径。", space_after=2)
para("教训：统计口径要写出来让人能质疑。「数字相加不等于总数」不是 bug，但不说清楚就是 bug。", size=9.5, color=MUTED)

